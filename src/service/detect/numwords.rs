/// Парсит последовательность слов-числительных в число. Возвращает None, если не число.
pub fn parse_numeral_words(words: &[&str]) -> Option<u32> {
    let dict = build_dict();
    let mut total: u32 = 0;
    let mut current: u32 = 0;
    let mut any = false;

    for w in words {
        let v = *dict.get(w)?;
        any = true;
        if v >= 1000 {
            let mult = if current == 0 { 1 } else { current };
            total += mult * v;
            current = 0;
        } else if v >= 100 {
            current = if current == 0 { v } else { current * v };
        } else {
            current += v;
        }
    }
    if !any {
        return None;
    }
    Some(total + current)
}

/// Парсит год прописью: «тысяча девятьсот восемьдесят пятого».
pub fn parse_year_words(words: &[&str]) -> Option<u32> {
    parse_numeral_words(words)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_numbers() {
        assert_eq!(parse_numeral_words(&["пятого"]), Some(5));
        assert_eq!(
            parse_numeral_words(&["тысяча", "девятьсот", "восемьдесят", "пятого"]),
            Some(1985)
        );
        assert_eq!(parse_numeral_words(&["две", "тысячи", "третьего"]), Some(2003));
        assert_eq!(parse_numeral_words(&["тридцать", "первого"]), Some(31));
    }
}